pub fn generate(ctx: &Ctx) -> Result<()> {
    let t = &ctx.t;
    for m in Mode::ALL {
        let vars = vars(t, m);
        let theme = format!("share/themes/Lumen-{}", m.title());
        let common = subst(COMMON, &vars);
        ctx.write(format!("{theme}/gtk-3.0/gtk.css"), format!("{}{common}{}", subst(HEADER, &vars), subst(GTK3, &vars)))?;
        ctx.write(format!("{theme}/gtk-4.0/gtk.css"), format!("{}{common}{}", subst(HEADER, &vars), subst(GTK4, &vars)))?;
        ctx.write(
            format!("{theme}/index.theme"),
            format!(
                "[Desktop Entry]\nType=X-GNOME-Metatheme\nName=Lumen {0}\nComment=Lumen {0} GTK theme\nEncoding=UTF-8\n\n[X-GNOME-Metatheme]\nGtkTheme=Lumen-{0}\n",
                m.title()
            ),
        )?;
        ctx.write(format!("config/gtk-4.0/lumen-{}.css", m.name()), subst(ADWAITA, &vars))?;
    }
    Ok(())
}

fn subst(tpl: &str, vars: &[(String, String)]) -> String {
    let mut out = String::with_capacity(tpl.len() + 1024);
    let mut rest = tpl;
    while let Some(i) = rest.find('{') {
        out.push_str(&rest[..i]);
        let after = &rest[i + 1..];
        match after.find('}') {
            Some(j) if after[..j].chars().all(|c| c.is_ascii_alphanumeric() || c == '_') && j > 0 => {
                let key = &after[..j];
                let v = vars.iter().find(|(k, _)| k == key).map(|(_, v)| v.as_str()).unwrap_or_else(|| panic!("gtk template var {key}"));
                out.push_str(v);
                rest = &after[j + 1..];
            }
            _ => {
                out.push('{');
                rest = after;
            }
        }
    }
    out.push_str(rest);
    out
}

fn vars(t: &Tokens, m: Mode) -> Vec<(String, String)> {
    let dark = m == Mode::Dark;
    let sh = accent_shades(t, t.color("accent.default"));
    let mut v: Vec<(String, String)> = Vec::new();
    let mut put = |k: &str, val: String| v.push((k.to_owned(), val));
    for k in t.table("color.dark").keys() {
        put(&format!("c_{k}"), t.c(m, k).css());
    }
    for k in t.table("palette.dark").keys() {
        put(&format!("p_{k}"), t.p(m, k).css());
    }
    put("accent", sh.base.hex());
    put("accent_fill", sh.fill(dark).hex());
    put("accent_text", sh.text(dark).hex());
    put("accent_mix", if dark { "mix(@accent, white, 0.38)".into() } else { "shade(@accent, 0.82)".into() });
    put("accent_text_mix", if dark { "mix(@accent, white, 0.55)".into() } else { "shade(@accent, 0.65)".into() });
    put("dark", if dark { "true".into() } else { "false".into() });
    put("scheme", if dark { "dark".into() } else { "light".into() });
    let px = |k: &str| format!("{}px", fmt_num(t.f(k)));
    put("r_control", px("radius.control"));
    put("r_overlay", px("radius.overlay"));
    put("r_window", px("radius.window"));
    put("r_tooltip", px("radius.tooltip"));
    put("menu_item_h", px("size.menu_item_h"));
    put("control_h", px("size.control_h"));
    put("font", t.s("font.ui").to_owned());
    put("ms_fast", format!("{}ms", t.i("motion.fast_ms")));
    put("ms_faster", format!("{}ms", t.i("motion.faster_ms")));
    put("ease", {
        let b = t.fv("motion.decel");
        format!("cubic-bezier({}, {}, {}, {})", fmt_num(b[0]), fmt_num(b[1]), fmt_num(b[2]), fmt_num(b[3]))
    });
    let shadow = |key: &str| {
        let col = if dark { 3 } else { 4 };
        t.fvv(&format!("shadow.{key}"))
            .iter()
            .map(|r| format!("0 {}px {}px {}", fmt_num(r[1]), fmt_num(r[2]), Rgba::BLACK.alpha(r[col]).css()))
            .collect::<Vec<_>>()
            .join(", ")
    };
    put("shadow_window", shadow("window_active"));
    // GTK sizes a client-decorated window's buffer to its shadow, so a smaller unfocused shadow resized the whole
    // window on every focus change (the edge blinked when Start opened). Unfocused keeps the geometry, lighter.
    let col = if dark { 3 } else { 4 };
    let active = t.fvv("shadow.window_active");
    let inactive = t.fvv("shadow.window_inactive");
    put(
        "shadow_window_inactive",
        active
            .iter()
            .zip(&inactive)
            .map(|(a, i)| format!("0 {}px {}px {}", fmt_num(a[1]), fmt_num(a[2]), Rgba::BLACK.alpha(i[col]).css()))
            .collect::<Vec<_>>()
            .join(", "),
    );
    put("shadow_flyout", shadow("flyout"));
    put("shadow_tooltip", shadow("tooltip"));
    put("menu_alpha", fmt_num(t.fm("surface.menu_alpha", m)));
    v
}

