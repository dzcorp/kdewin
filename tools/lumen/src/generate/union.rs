use crate::ctx::Ctx;
use crate::tokens::fmt_num;
use anyhow::Result;
use std::path::Path;

const BREEZE: &str = "/usr/share/union/styles/breeze";

/// Union (KDE's CSS style engine, beta in 6.8): Breeze's BSD-2 rule set + Lumen variable overrides.
pub fn generate(ctx: &Ctx) -> Result<()> {
    let src = Path::new(BREEZE);
    if !src.is_dir() {
        println!("  union: {BREEZE} not found, skipped");
        return Ok(());
    }
    let dst = "share/union/styles/lumen";
    for entry in walkdir::WalkDir::new(src).into_iter().filter_map(|e| e.ok()).filter(|e| e.file_type().is_file()) {
        let rel = entry.path().strip_prefix(src)?;
        if rel == Path::new("metadata.json") {
            continue;
        }
        let mut data = std::fs::read(entry.path())?;
        if rel == Path::new("contents/css/style.css") {
            data.extend_from_slice(b"\n@import \"lumen.css\";\n");
        }
        ctx.write(Path::new(dst).join(rel), data)?;
    }
    let t = &ctx.t;
    let px = |k: &str| format!("{}px", fmt_num(t.f(k)));
    ctx.write(
        format!("{dst}/metadata.json"),
        format!(
            r#"{{
    "input-type": "css",
    "input-version": 1,
    "name": "Lumen (Union)",
    "description": "Lumen Fluent-inspired style for KDE Plasma (Union engine).",
    "version": "{}",
    "license": "BSD-2-Clause",
    "url": "{}",
    "authors": ["{}", "Breeze (Union) authors"]
}}
"#,
            ctx.version(),
            t.s("meta.website"),
            t.s("meta.author")
        ),
    )?;
    ctx.write(
        format!("{dst}/contents/css/lumen.css"),
        format!(
            r#"/* Lumen overrides — generated by `lumen gen`. */
:root {{
    --corner-radius: {r};
    --scrollbar-size: {sb};
    --non-interactive-scrollbar-size: {sbr};
    --focus-outline-alpha: 1;
    --card-hover-color: mix(var(--card-background-color), var(--window-text-color), 0.05);
    --card-pressed-color: mix(var(--card-background-color), var(--window-text-color), 0.03);
    --window-highlight-color: mix(var(--window-background-color), var(--window-text-color), 0.06);
    --view-highlight-color: mix(var(--view-background-color), var(--window-text-color), 0.06);
    --highlight-hover-color: mix(var(--window-background-color), var(--window-text-color), 0.06);
}}
"#,
            r = px("radius.control"),
            sb = px("size.scrollbar"),
            sbr = px("size.scrollbar_hover"),
        ),
    )
}
