use crate::color::Rgba;
use crate::ctx::Ctx;
use crate::tokens::{Mode, fmt_num};
use anyhow::Result;
use std::fmt::Write;
use toml::Value;

pub fn generate(ctx: &Ctx) -> Result<()> {
    let t = &ctx.t;
    let mut h = String::with_capacity(16 * 1024);
    h.push_str("// Generated by `lumen gen` from tokens/tokens.toml. Do not edit.\n#pragma once\n#include <cstdint>\n\nnamespace Lumen::T\n{\n");
    writeln!(h, "inline constexpr const char *Version = \"{}\";\n", ctx.version())?;
    writeln!(h, "inline constexpr const char *OpaqueApps = \"{}\";\n", super::kcfg::OPAQUE_APPS)?;

    for ns in ["radius", "size", "motion", "font", "type", "boot"] {
        namespace(&mut h, ns, t.table(ns))?;
    }

    h.push_str("struct Rgb { std::uint32_t argb; };\n\n");
    namespace_colors(&mut h, "Accent", t.table("accent"))?;

    h.push_str("struct Layer { double x, y, blur, alpha; };\n\nnamespace Shadow\n{\n");
    for (k, _) in t.table("shadow") {
        let rows = t.fvv(&format!("shadow.{k}"));
        for m in Mode::ALL {
            let col = if m == Mode::Dark { 3 } else { 4 };
            let items: Vec<String> = rows
                .iter()
                .map(|r| format!("{{{}, {}, {}, {}}}", fmt_num(r[0]), fmt_num(r[1]), fmt_num(r[2]), fmt_num(r[col])))
                .collect();
            writeln!(h, "inline constexpr Layer {}{}[] = {{{}}};", pascal(k), m.title(), items.join(", "))?;
        }
    }
    h.push_str("}\n\n");

    h.push_str("struct Material { std::uint32_t tint; double tintOpacity, luminosityOpacity; std::uint32_t fallback; };\n\nnamespace Materials\n{\n");
    for (name, v) in t.table("material") {
        let tbl = v.as_table().unwrap();
        for (k, val) in tbl {
            if let Some(n) = val.as_float().or(val.as_integer().map(|i| i as f64)) {
                writeln!(h, "inline constexpr double {}{} = {};", pascal(name), pascal(k), fmt_num(n))?;
            }
        }
        for m in Mode::ALL {
            let p = format!("material.{name}.{}", m.name());
            writeln!(
                h,
                "inline constexpr Material {}{}{{0x{:08x}u, {}, {}, 0x{:08x}u}};",
                pascal(name),
                m.title(),
                t.color(&format!("{p}.tint")).argb_u32(),
                fmt_num(t.f(&format!("{p}.tint_opacity"))),
                fmt_num(t.f(&format!("{p}.luminosity_opacity"))),
                t.color(&format!("{p}.fallback")).argb_u32()
            )?;
        }
    }
    h.push_str("}\n\nnamespace Surface\n{\n");
    for (k, _) in t.table("surface") {
        for m in Mode::ALL {
            writeln!(h, "inline constexpr double {}{} = {};", pascal(k), m.title(), fmt_num(t.fm(&format!("surface.{k}"), m)))?;
        }
    }
    h.push_str("}\n\n");

    let keys: Vec<&String> = t.table("color.dark").keys().collect();
    h.push_str("// Fluent semantic colors, 0xAARRGGBB.\nstruct Fluent\n{\n");
    for k in &keys {
        writeln!(h, "    std::uint32_t {};", camel(k))?;
    }
    h.push_str("};\n\n");
    for m in Mode::ALL {
        writeln!(h, "inline constexpr Fluent {}{{", m.title())?;
        for k in &keys {
            writeln!(h, "    0x{:08x}u, // {k}", t.c(m, k).argb_u32())?;
        }
        h.push_str("};\n\n");
    }

    let pkeys: Vec<&String> = t.table("palette.dark").keys().collect();
    h.push_str("struct Palette\n{\n");
    for k in &pkeys {
        writeln!(h, "    std::uint32_t {};", camel(k))?;
    }
    h.push_str("};\n\n");
    for m in Mode::ALL {
        writeln!(h, "inline constexpr Palette Palette{}{{", m.title())?;
        for k in &pkeys {
            writeln!(h, "    0x{:08x}u,", t.p(m, k).argb_u32())?;
        }
        h.push_str("};\n\n");
    }

    h.push_str("} // namespace Lumen::T\n");
    ctx.write_gen("cpp/lumentokens.h", h)
}

fn namespace(h: &mut String, ns: &str, tbl: &toml::Table) -> Result<()> {
    writeln!(h, "namespace {}\n{{", pascal(ns))?;
    for (k, v) in tbl {
        let name = pascal(k);
        match v {
            Value::Integer(i) => writeln!(h, "inline constexpr double {name} = {i};")?,
            Value::Float(f) => writeln!(h, "inline constexpr double {name} = {};", fmt_num(*f))?,
            Value::String(s) => match Rgba::parse(s) {
                Ok(c) if s.starts_with('#') => writeln!(h, "inline constexpr std::uint32_t {name} = 0x{:08x}u;", c.argb_u32())?,
                _ => writeln!(h, "inline constexpr const char *{name} = \"{}\";", s.replace('"', "\\\""))?,
            },
            Value::Boolean(b) => writeln!(h, "inline constexpr bool {name} = {b};")?,
            Value::Array(a) => {
                if a.iter().all(|x| x.is_str()) {
                    let items: Vec<String> = a.iter().map(|x| format!("\"{}\"", x.as_str().unwrap())).collect();
                    writeln!(h, "inline constexpr const char *{name}[] = {{{}}};", items.join(", "))?;
                } else if a.iter().all(|x| x.is_integer() || x.is_float()) {
                    let items: Vec<String> =
                        a.iter().map(|x| fmt_num(x.as_float().unwrap_or_else(|| x.as_integer().unwrap() as f64))).collect();
                    writeln!(h, "inline constexpr double {name}[] = {{{}}};", items.join(", "))?;
                }
            }
            _ => {}
        }
    }
    h.push_str("}\n\n");
    Ok(())
}

fn namespace_colors(h: &mut String, ns: &str, tbl: &toml::Table) -> Result<()> {
    writeln!(h, "namespace {ns}\n{{")?;
    for (k, v) in tbl {
        let name = pascal(k);
        match v {
            Value::String(s) => writeln!(h, "inline constexpr std::uint32_t {name} = 0x{:08x}u;", Rgba::parse(s)?.argb_u32())?,
            Value::Float(f) => writeln!(h, "inline constexpr double {name} = {};", fmt_num(*f))?,
            Value::Array(a) => {
                let items: Vec<String> = a.iter().map(|x| fmt_num(x.as_float().unwrap_or(0.0))).collect();
                writeln!(h, "inline constexpr double {name}[] = {{{}}};", items.join(", "))?;
            }
            _ => {}
        }
    }
    h.push_str("}\n\n");
    Ok(())
}

pub fn pascal(s: &str) -> String {
    s.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next().map(|f| f.to_uppercase().chain(c).collect::<String>()).unwrap_or_default()
        })
        .collect()
}

pub fn camel(s: &str) -> String {
    let p = pascal(s);
    let mut c = p.chars();
    c.next().map(|f| f.to_lowercase().chain(c).collect()).unwrap_or_default()
}
