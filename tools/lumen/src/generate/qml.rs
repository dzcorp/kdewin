const JS: &str = r#"
    function _lin(c) { return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4) }
    function _gam(c) { c = Math.min(1, Math.max(0, c)); return c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055 }
    function oklab(c) {
        const r = _lin(c.r), g = _lin(c.g), b = _lin(c.b)
        const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
        const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
        const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
        return [0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
                1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
                0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s]
    }
    function withLightness(c, L) {
        const lab = oklab(c)
        let k = 1
        for (let i = 0; i < 64; ++i, k *= 0.95) {
            const a = lab[1] * k, b = lab[2] * k
            const l = Math.pow(L + 0.3963377774 * a + 0.2158037573 * b, 3)
            const m = Math.pow(L - 0.1055613458 * a - 0.0638541728 * b, 3)
            const s = Math.pow(L - 0.0894841775 * a - 1.2914855480 * b, 3)
            const R = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
            const G = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
            const B = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
            if (Math.min(R, G, B) >= -1e-4 && Math.max(R, G, B) <= 1 + 1e-4 || i === 63)
                return Qt.rgba(_gam(R), _gam(G), _gam(B), c.a)
        }
    }
    function lightness(c) { return oklab(c)[0] }
    // index: 0..2 light1..light3, 3..5 dark1..dark3
    // The Windows default accent uses its published shades, like the C++ side (lumencolor.cpp).
    function accentShade(c, index) {
        if (Qt.colorEqual(Qt.rgba(c.r, c.g, c.b, 1), accentDefault))
            return accentPreset[index]
        const L = lightness(c)
        return index < 3 ? withLightness(c, L + (accentLmax - L) * accentLightF[index])
                         : withLightness(c, L * accentDarkF[index - 3])
    }
    function alpha(c, a) { return Qt.rgba(c.r, c.g, c.b, c.a * a) }
"#;

pub fn qml_tokens(t: &Tokens) -> String {
    let mut q = String::with_capacity(16 * 1024);
    q.push_str("// Generated by `lumen gen` from tokens/tokens.toml. Do not edit.\nimport QtQuick\nimport org.kde.kirigami as Kirigami\n\nQtObject {\n");
    q.push_str("    property color reference: Kirigami.Theme.backgroundColor\n");
    q.push_str("    readonly property bool dark: lightness(reference) < 0.5\n");
    q.push_str("    readonly property color accent: Kirigami.Theme.highlightColor\n");
    writeln!(q, "    readonly property color accentDefault: \"{}\"", t.s("accent.default")).unwrap();
    let preset: Vec<String> = ["light1", "light2", "light3", "dark1", "dark2", "dark3"].iter().map(|k| format!("\"{}\"", t.s(&format!("accent.{k}")))).collect();
    writeln!(q, "    readonly property var accentPreset: [{}]", preset.join(", ")).unwrap();
    writeln!(q, "    readonly property real accentLmax: {}", fmt_num(t.f("accent.lmax"))).unwrap();
    writeln!(q, "    readonly property var accentLightF: [{}]", join(&t.fv("accent.light_f"))).unwrap();
    writeln!(q, "    readonly property var accentDarkF: [{}]", join(&t.fv("accent.dark_f"))).unwrap();
    for (i, n) in ["Light1", "Light2", "Light3", "Dark1", "Dark2", "Dark3"].iter().enumerate() {
        writeln!(q, "    readonly property color accent{n}: accentShade(accent, {i})").unwrap();
    }
    q.push_str(
        "    readonly property color accentFill: dark ? accentLight2 : accentDark1\n\
         \x20   readonly property color accentFillHover: alpha(accentFill, 0.9)\n\
         \x20   readonly property color accentFillPressed: alpha(accentFill, 0.8)\n\
         \x20   readonly property color accentText: dark ? accentLight3 : accentDark2\n",
    );

    for ns in ["radius", "size", "motion", "font", "type"] {
        q.push('\n');
        for (k, v) in t.table(ns) {
            let name = format!("{ns}_{k}");
            if let Some(line) = prop(&camel(&name), v) {
                q.push_str(&line);
            }
        }
    }
    q.push('\n');
    writeln!(q, "    readonly property int easingDecel: Easing.{}", t.s("motion.qt_decel")).unwrap();
    writeln!(q, "    readonly property int easingAccel: Easing.{}", t.s("motion.qt_accel")).unwrap();
    writeln!(q, "    readonly property int easingPoint: Easing.{}", t.s("motion.qt_point")).unwrap();
    for c in ["decel", "point", "accel"] {
        writeln!(q, "    readonly property var bezier{}: [{}, 1, 1]", super::cpp::pascal(c), join(&t.fv(&format!("motion.{c}")))).unwrap();
    }

    q.push('\n');
    let path: Vec<f64> = super::boot::spin_path(t, 97).iter().map(|a| (a * 10.0).round() / 10.0).collect();
    writeln!(q, "    readonly property var bootSpinPath: [{}]", join(&path)).unwrap();
    writeln!(q, "    readonly property int bootSpinDots: {}", t.i("boot.spinner_dots")).unwrap();
    writeln!(q, "    readonly property int bootSpinMs: {}", t.i("boot.spinner_frames") * 1000 / 30).unwrap();
    for k in ["life", "lag", "trail"] {
        writeln!(q, "    readonly property real bootSpin{}: {}", super::cpp::pascal(k), fmt_num(t.f(&format!("boot.spinner_{k}")))).unwrap();
    }

    q.push('\n');
    for (k, _) in t.table("surface") {
        writeln!(
            q,
            "    readonly property real {}: dark ? {} : {}",
            camel(k),
            fmt_num(t.fm(&format!("surface.{k}"), Mode::Dark)),
            fmt_num(t.fm(&format!("surface.{k}"), Mode::Light))
        )
        .unwrap();
    }

    q.push('\n');
    for (k, _) in t.table("color.dark") {
        writeln!(q, "    readonly property color {}: dark ? \"{}\" : \"{}\"", camel(k), t.c(Mode::Dark, k).argb(), t.c(Mode::Light, k).argb())
            .unwrap();
    }
    for (k, _) in t.table("palette.dark") {
        writeln!(
            q,
            "    readonly property color {}: dark ? \"{}\" : \"{}\"",
            camel(&format!("palette_{k}")),
            t.p(Mode::Dark, k).argb(),
            t.p(Mode::Light, k).argb()
        )
        .unwrap();
    }
    for name in ["acrylic", "acrylic_base", "mica", "mica_alt"] {
        for f in ["tint", "fallback"] {
            let d = t.color(&format!("material.{name}.dark.{f}"));
            let l = t.color(&format!("material.{name}.light.{f}"));
            writeln!(q, "    readonly property color {}: dark ? \"{}\" : \"{}\"", camel(&format!("{name}_{f}")), d.argb(), l.argb()).unwrap();
        }
    }

    q.push_str(JS);
    q.push_str("}\n");
    q
}

fn prop(name: &str, v: &Value) -> Option<String> {
    Some(match v {
        Value::Integer(i) => format!("    readonly property real {name}: {i}\n"),
        Value::Float(f) => format!("    readonly property real {name}: {}\n", fmt_num(*f)),
        Value::String(s) => format!("    readonly property string {name}: \"{}\"\n", s.replace('"', "\\\"")),
        Value::Boolean(b) => format!("    readonly property bool {name}: {b}\n"),
        Value::Array(a) => {
            let items: Vec<String> = a
                .iter()
                .map(|x| match x {
                    Value::String(s) => format!("\"{s}\""),
                    Value::Integer(i) => i.to_string(),
                    Value::Float(f) => fmt_num(*f),
                    _ => "null".into(),
                })
                .collect();
            format!("    readonly property var {name}: [{}]\n", items.join(", "))
        }
        _ => return None,
    })
}

fn join(v: &[f64]) -> String {
    v.iter().map(|x| fmt_num(*x)).collect::<Vec<_>>().join(", ")
}
